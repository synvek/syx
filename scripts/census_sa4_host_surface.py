#!/usr/bin/env python3
"""SA-4 census: public packages must not spell `__syx_*` (hosts live under packages/internal/)."""
from __future__ import annotations
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALLOW_DIRS = {"packages/internal"}
# Generated aggregates may embed host when regenerated with it; prefer public-only.
ALLOW_FILES = set()

HOST_RE = re.compile(r"__syx_[A-Za-z0-9_]+")


def main() -> int:
    hits: list[tuple[str, int]] = []
    for path in sorted((ROOT / "packages").rglob("*.sy")):
        rel = path.relative_to(ROOT).as_posix()
        if any(rel.startswith(d + "/") or rel == d for d in ALLOW_DIRS):
            continue
        if rel in ALLOW_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        n = len(HOST_RE.findall(text))
        if n:
            hits.append((rel, n))
    out = ROOT / "docs/census/sa-4-host-surface.md"
    lines = [
        "# SA-4 host surface census",
        "",
        "Authority: `packages/internal/*_host.sy` may contain `__syx_*`.",
        "All other `packages/**/*.sy` must be zero.",
        "",
        f"Generated by `scripts/census_sa4_host_surface.py`.",
        "",
    ]
    if hits:
        lines.append("## FAIL")
        lines.append("")
        for rel, n in hits:
            lines.append(f"- `{rel}`: {n}")
        lines.append("")
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"FAIL: {len(hits)} files still spell __syx_* (wrote {out})")
        return 1
    lines.append("## PASS")
    lines.append("")
    lines.append("- non-`packages/internal` `__syx_*` count: **0**")
    lines.append("")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PASS: wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
