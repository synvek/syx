#!/usr/bin/env python3
"""Generate books/shared/capabilities-generated.md (+ JSON for doctor) from capabilities.toml.

Minimal TOML subset parser (no tomllib) for CI on Python 3.9+.

Usage:
  python3 scripts/gen_capabilities.py
  python3 scripts/gen_capabilities.py --check
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "packages" / "internal" / "capabilities.toml"
OUT_MD = ROOT / "books" / "shared" / "capabilities-generated.md"
OUT_JSON = ROOT / "packages" / "internal" / "capabilities.generated.json"

STR_RE = re.compile(r'^(\w+)\s*=\s*"([^"]*)"\s*$')
INT_RE = re.compile(r"^(\w+)\s*=\s*(\d+)\s*$")
ARR_RE = re.compile(r"^(\w+)\s*=\s*\[(.*)\]\s*$")
BACKENDS_RE = re.compile(r"^backends\s*=\s*\{([^}]*)\}\s*$")

FEATURE_STATUSES = {
    "implemented",
    "partial",
    "experimental",
    "experimental-real-subset",
    "preview",
    "unsupported",
    "stub",
    "frozen",
}
BACKEND_STATUSES = {
    "real",
    "partial",
    "host-assisted",
    "stub",
    "unsupported",
    "noop",
}
WEAK_BACKENDS = {"noop", "stub", "unsupported"}
REQUIRED_BACKENDS = ("vm", "mir", "native", "wasm")


def parse_backends(inner: str) -> dict:
    out = {}
    for part in inner.split(","):
        part = part.strip()
        if not part:
            continue
        m = re.match(r'(\w+)\s*=\s*"([^"]*)"', part)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def parse_array(inner: str) -> list:
    items = []
    for m in re.finditer(r'"([^"]*)"', inner):
        items.append(m.group(1))
    return items


def load_capabilities(path: Path) -> dict:
    meta: dict = {}
    caps: list = []
    section = None
    current: dict | None = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line == "[meta]":
            if current is not None:
                caps.append(current)
                current = None
            section = "meta"
            continue
        if line == "[[capability]]":
            if current is not None:
                caps.append(current)
            current = {}
            section = "capability"
            continue

        target = meta if section == "meta" else current
        if target is None:
            continue

        m = BACKENDS_RE.match(line)
        if m:
            target["backends"] = parse_backends(m.group(1))
            continue
        m = ARR_RE.match(line)
        if m:
            target[m.group(1)] = parse_array(m.group(2))
            continue
        m = STR_RE.match(line)
        if m:
            target[m.group(1)] = m.group(2)
            continue
        m = INT_RE.match(line)
        if m:
            target[m.group(1)] = int(m.group(2))
            continue

    if current is not None:
        caps.append(current)
    return {"meta": meta, "capability": caps}


def validate_capabilities(data: dict) -> list[str]:
    """Return human-readable honesty / schema errors (empty = ok)."""
    errors: list[str] = []
    seen: set[str] = set()
    for cap in data.get("capability", []):
        cid = cap.get("id") or "<missing-id>"
        if cid in seen:
            errors.append(f"duplicate capability id: {cid}")
        seen.add(cid)
        status = cap.get("status") or ""
        if status not in FEATURE_STATUSES:
            errors.append(f"{cid}: unknown status {status!r}")
        backends = cap.get("backends") or {}
        for key in REQUIRED_BACKENDS:
            if key not in backends:
                errors.append(f"{cid}: missing backend column {key}")
        for key, val in backends.items():
            if val not in BACKEND_STATUSES:
                errors.append(f"{cid}: unknown backend status {key}={val!r}")
        if status == "implemented":
            weak = {k: v for k, v in backends.items() if v in WEAK_BACKENDS}
            if weak:
                errors.append(
                    f"{cid}: status=implemented but weak backends {weak} "
                    f"(use partial/experimental/experimental-real-subset)"
                )
    return errors


def render_md(data: dict) -> str:
    meta = data["meta"]
    lines = [
        "<!-- GENERATED by scripts/gen_capabilities.py — do not edit by hand -->",
        "",
        f"# Capability matrix (generated · schema {meta.get('schema', '?')})",
        "",
        f"> SYX **{meta.get('syx_version')}** · phase **{meta.get('phase')}** · manifest v{meta.get('version')}",
        "",
        "| ID | Feature | Status | VM | MIR | Native | WASM | Notes |",
        "|----|---------|--------|----|-----|--------|------|-------|",
    ]
    for cap in data.get("capability", []):
        b = cap.get("backends", {})
        notes = (cap.get("notes") or "").replace("|", "\\|")
        lines.append(
            "| {id} | {feature} | {status} | {vm} | {mir} | {native} | {wasm} | {notes} |".format(
                id=cap.get("id", ""),
                feature=cap.get("feature", ""),
                status=cap.get("status", ""),
                vm=b.get("vm", "—"),
                mir=b.get("mir", "—"),
                native=b.get("native", "—"),
                wasm=b.get("wasm", "—"),
                notes=notes,
            )
        )
    lines.append("")
    lines.append(
        "Source: [`packages/internal/capabilities.toml`](../../packages/internal/capabilities.toml)."
    )
    lines.append(
        "Schema: [`docs/capability-manifest-v0.md`](../../docs/capability-manifest-v0.md)."
    )
    lines.append("")
    return "\n".join(lines)


def render_json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="Fail if generated outputs differ")
    args = ap.parse_args()
    data = load_capabilities(SRC)
    errors = validate_capabilities(data)
    if errors:
        for e in errors:
            print(f"INVALID: {e}", file=sys.stderr)
        return 1
    md = render_md(data)
    js = render_json(data)
    if args.check:
        ok = True
        if not OUT_MD.exists() or OUT_MD.read_text(encoding="utf-8") != md:
            print(f"STALE: {OUT_MD}", file=sys.stderr)
            ok = False
        if not OUT_JSON.exists() or OUT_JSON.read_text(encoding="utf-8") != js:
            print(f"STALE: {OUT_JSON}", file=sys.stderr)
            ok = False
        return 0 if ok else 1
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(md, encoding="utf-8")
    OUT_JSON.write_text(js, encoding="utf-8")
    print(f"wrote {OUT_MD.relative_to(ROOT)}")
    print(f"wrote {OUT_JSON.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
