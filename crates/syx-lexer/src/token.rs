use smol_str::SmolStr;
use syx_diagnostics::Span;

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    // Declarations
    Class,
    Struct,
    Enum,
    Protocol,
    Extension,
    Func,
    Init,
    Deinit,
    Var,
    Let,
    Import,
    /// W480 / ADR-824: `export func …` declaration keyword.
    Export,
    Public,
    Internal,
    Private,
    FilePrivate,
    Static,
    // Control flow
    Async,
    Await,
    Task,
    Actor,
    Global,
    Isolated,
    Sending,
    Data,
    Final,
    Where,
    Requires,
    Pure,
    Io,
    Service,
    Macro,
    Typealias,
    Subscript,
    CompileTime,
    If,
    Else,
    Guard,
    Switch,
    Select,
    Case,
    Default,
    /// Phase 111: `timeout(ms):` arm inside `select`.
    Timeout,
    /// Phase 111: `deadline ms:` arm inside `select`.
    Deadline,
    For,
    In,
    While,
    Repeat,
    Break,
    Continue,
    Return,
    // Error handling
    Try,
    Throw,
    Throws,
    Catch,
    // Types
    SelfKw,
    SuperKw,
    SelfType,
    Type,
    ProtocolKw,
    // Modifiers
    Weak,
    Unowned,
    Mutating,
    // Literals
    Integer(i128, Option<SmolStr>),
    /// Wide decimal integer with `n` suffix (Phase 48).
    BigIntLiteral(String),
    Double(f64, Option<SmolStr>),
    String(String),
    InterpolatedString(Vec<InterpPart>),
    Regex(String),
    Bool(bool),
    Nil,
    // Identifiers
    Identifier(SmolStr),
    /// Lifetime annotation (`'a`) for reference types (Phase 15 MVP).
    Lifetime(SmolStr),
    // Operators
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Assign,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    PercentEqual,
    AmpEqual,
    PipeEqual,
    CaretEqual,
    LessLessEqual,
    GreaterGreaterEqual,
    Pipe,
    Caret,
    Tilde,
    EqualEqual,
    EqualEqualEqual,
    NotEqual,
    NotEqualEqual,
    Less,
    LessEqual,
    LessLess,
    Greater,
    GreaterEqual,
    GreaterGreater,
    AndAnd,
    OrOr,
    Bang,
    Question,
    NilCoalesce,
    Arrow,
    FatArrow,
    Dot,
    DotDotDot,
    DotDotLess,
    Range,
    // Delimiters
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Colon,
    Semicolon,
    At,
    Hash,
    Amp,
    Backslash,
    /// Phase 43: cast keyword (`as` / `as?`).
    As,
    /// Phase 60: type check keyword (`is`).
    Is,
    // Special
    Eof,
    Newline,
    /// ADR-142: `//` line comment (lexeme includes `//…`).
    LineComment,
    /// ADR-142: `/* … */` block comment (lexeme includes delimiters).
    BlockComment,
    /// ADR-142: run of space/tab (for CST round-trip).
    Whitespace,
}

#[derive(Debug, Clone, PartialEq)]
pub enum InterpPart {
    Text(String),
    Expr(String),
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub lexeme: SmolStr,
    pub span: Span,
    pub line: usize,
    pub column: usize,
}

impl Token {
    pub fn dummy(kind: TokenKind) -> Self {
        Self {
            kind,
            lexeme: SmolStr::default(),
            span: Span::DUMMY,
            line: 0,
            column: 0,
        }
    }
}

pub fn keyword(text: &str) -> Option<TokenKind> {
    Some(match text {
        "class" => TokenKind::Class,
        "struct" => TokenKind::Struct,
        "enum" => TokenKind::Enum,
        "protocol" => TokenKind::Protocol,
        "extension" => TokenKind::Extension,
        "func" => TokenKind::Func,
        "init" => TokenKind::Init,
        "deinit" => TokenKind::Deinit,
        "var" => TokenKind::Var,
        "let" => TokenKind::Let,
        "import" => TokenKind::Import,
        "export" => TokenKind::Export,
        "public" => TokenKind::Public,
        "internal" => TokenKind::Internal,
        "private" => TokenKind::Private,
        "fileprivate" => TokenKind::FilePrivate,
        "static" => TokenKind::Static,
        "async" => TokenKind::Async,
        "await" => TokenKind::Await,
        "Task" => TokenKind::Task,
        "actor" => TokenKind::Actor,
        "global" => TokenKind::Global,
        "isolated" => TokenKind::Isolated,
        "sending" => TokenKind::Sending,
        "data" => TokenKind::Data,
        "final" => TokenKind::Final,
        "where" => TokenKind::Where,
        "requires" => TokenKind::Requires,
        "Pure" => TokenKind::Pure,
        "IO" => TokenKind::Io,
        "Service" => TokenKind::Service,
        "macro" => TokenKind::Macro,
        "typealias" => TokenKind::Typealias,
        "subscript" => TokenKind::Subscript,
        "if" => TokenKind::If,
        "else" => TokenKind::Else,
        "guard" => TokenKind::Guard,
        "switch" => TokenKind::Switch,
        "select" => TokenKind::Select,
        "case" => TokenKind::Case,
        "default" => TokenKind::Default,
        "timeout" => TokenKind::Timeout,
        "deadline" => TokenKind::Deadline,
        "for" => TokenKind::For,
        "in" => TokenKind::In,
        "while" => TokenKind::While,
        "repeat" => TokenKind::Repeat,
        "break" => TokenKind::Break,
        "continue" => TokenKind::Continue,
        "return" => TokenKind::Return,
        "try" => TokenKind::Try,
        "throw" => TokenKind::Throw,
        "throws" => TokenKind::Throws,
        "catch" => TokenKind::Catch,
        "self" => TokenKind::SelfKw,
        "super" => TokenKind::SuperKw,
        "Self" => TokenKind::SelfType,
        "type" => TokenKind::Type,
        "Protocol" => TokenKind::ProtocolKw,
        "weak" => TokenKind::Weak,
        "unowned" => TokenKind::Unowned,
        "mutating" => TokenKind::Mutating,
        "true" => TokenKind::Bool(true),
        "false" => TokenKind::Bool(false),
        "nil" => TokenKind::Nil,
        "as" => TokenKind::As,
        "is" => TokenKind::Is,
        _ => return None,
    })
}
